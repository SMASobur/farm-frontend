import { useState, useRef, useEffect } from 'react';
import { X, Upload, Loader2, Trash2, Image as ImageIcon } from 'lucide-react';
import { useMutation, useQueryClient } from '@tanstack/react-query';
import { uploadFarmLogo, removeFarmLogo } from '@/api/farms';
import { useToast } from '@/contexts/ToastContext';

interface Props {
    currentLogoUrl: string | null;
    farmName: string;
    onClose: () => void;
}

export function FarmLogoModal({ currentLogoUrl, farmName, onClose }: Props) {
    const queryClient = useQueryClient();
    const toast = useToast();
    const fileInputRef = useRef<HTMLInputElement>(null);

    const [preview, setPreview] = useState<string | null>(currentLogoUrl);
    const [selectedFile, setSelectedFile] = useState<File | null>(null);
    const [error, setError] = useState('');

    useEffect(() => {
        const handler = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
        window.addEventListener('keydown', handler);
        return () => window.removeEventListener('keydown', handler);
    }, [onClose]);

    useEffect(() => {
        document.body.style.overflow = 'hidden';
        return () => { document.body.style.overflow = ''; };
    }, []);

    const uploadMutation = useMutation({
        mutationFn: (file: File) => uploadFarmLogo(file),
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: ['farm'] });
            toast.success('Logo updated');
            onClose();
        },
        onError: (err: any) => {
            setError(err.response?.data?.message || 'Upload failed');
        },
    });

    const removeMutation = useMutation({
        mutationFn: () => removeFarmLogo(),
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: ['farm'] });
            toast.success('Logo removed');
            onClose();
        },
        onError: (err: any) => {
            setError(err.response?.data?.message || 'Failed to remove');
        },
    });

    const handleFileSelect = (e: React.ChangeEvent<HTMLInputElement>) => {
        const file = e.target.files?.[0];
        if (!file) return;
        setSelectedFile(file);
        setPreview(URL.createObjectURL(file));
        setError('');
    };

    const handleUpload = () => {
        if (!selectedFile) return;
        uploadMutation.mutate(selectedFile);
    };

    const loading = uploadMutation.isPending || removeMutation.isPending;

    return (
        <div
            className="fixed inset-0 z-50 bg-black/40 flex items-end md:items-center justify-center p-0 md:p-4"
            onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}
        >
            <div className="bg-white rounded-t-2xl md:rounded-2xl w-full md:max-w-md max-h-[90vh] overflow-y-auto">
                <div className="sticky top-0 bg-white border-b border-gray-100 p-4 flex items-center justify-between">
                    <h2 className="font-bold text-gray-900">Farm Logo</h2>
                    <button
                        onClick={onClose}
                        className="p-1.5 hover:bg-gray-100 rounded-lg transition text-gray-500"
                        aria-label="Close"
                    >
                        <X size={18} />
                    </button>
                </div>

                <div className="p-4 space-y-4">
                    {error && (
                        <div className="bg-red-50 text-red-700 text-sm p-3 rounded-lg border border-red-100">
                            {error}
                        </div>
                    )}

                    <p className="text-sm text-gray-500">
                        Your logo appears on all PDFs generated by <span className="font-medium">{farmName}</span>.
                    </p>

                    {/* Preview */}
                    <div className="flex justify-center">
                        {preview ? (
                            <div className="relative">
                                <img
                                    src={preview}
                                    alt="Logo preview"
                                    className="w-32 h-32 object-cover rounded-2xl border border-gray-200"
                                />
                            </div>
                        ) : (
                            <div className="w-32 h-32 rounded-2xl border-2 border-dashed border-gray-200 flex items-center justify-center text-gray-300">
                                <ImageIcon size={32} />
                            </div>
                        )}
                    </div>

                    {/* File select */}
                    <input
                        ref={fileInputRef}
                        type="file"
                        accept="image/png,image/jpeg,image/jpg"
                        onChange={handleFileSelect}
                        className="hidden"
                    />

                    <button
                        type="button"
                        onClick={() => fileInputRef.current?.click()}
                        disabled={loading}
                        className="w-full border border-gray-200 hover:border-gray-400 rounded-lg py-2.5 text-sm font-medium text-gray-700 disabled:opacity-50 transition inline-flex items-center justify-center gap-2"
                    >
                        <Upload size={16} />
                        {preview ? 'Choose Different Image' : 'Choose Image'}
                    </button>

                    <p className="text-xs text-gray-400 text-center">
                        PNG or JPG · Max 5 MB · Square recommended
                    </p>

                    {/* Actions */}
                    <div className="flex items-center gap-2 pt-2">
                        {selectedFile && (
                            <button
                                type="button"
                                onClick={handleUpload}
                                disabled={loading}
                                className="flex-1 bg-green-600 text-white py-2.5 rounded-lg font-medium hover:bg-green-700 disabled:opacity-50 transition inline-flex items-center justify-center gap-2"
                            >
                                {uploadMutation.isPending ? (
                                    <><Loader2 size={16} className="animate-spin" />Uploading…</>
                                ) : (
                                    <>Save Logo</>
                                )}
                            </button>
                        )}

                        {currentLogoUrl && !selectedFile && (
                            <button
                                type="button"
                                onClick={() => removeMutation.mutate()}
                                disabled={loading}
                                className="flex-1 border border-red-200 text-red-600 py-2.5 rounded-lg font-medium hover:bg-red-50 disabled:opacity-50 transition inline-flex items-center justify-center gap-2"
                            >
                                {removeMutation.isPending ? (
                                    <><Loader2 size={16} className="animate-spin" />Removing…</>
                                ) : (
                                    <><Trash2 size={16} />Remove</>
                                )}
                            </button>
                        )}

                        <button
                            type="button"
                            onClick={onClose}
                            disabled={loading}
                            className="px-4 py-2.5 rounded-lg font-medium text-gray-700 hover:bg-gray-100 disabled:opacity-50 transition"
                        >
                            Cancel
                        </button>
                    </div>
                </div>
            </div>
        </div>
    );
}